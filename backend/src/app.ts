import cors from 'cors';
import express from 'express';
import helmet from 'helmet';
import morgan from 'morgan';
import { errorMiddleware } from './middlewares/error.middleware';
import { rateLimitMiddleware } from './middlewares/rate-limit.middleware';
import { authRouter } from './modules/auth/auth.route';
import { usersRouter } from './modules/users/route';
import { booksRouter } from './modules/books/route';
import { categoriesRouter } from './modules/categories/route';
import { authorsRouter } from './modules/authors/route';
import { borrowRecordsRouter } from './modules/borrow-records/route';
import { reservationsRouter } from './modules/reservations/route';
import { finesRouter } from './modules/fines/route';

export const app = express();
app.use(cors());
app.use(helmet());
app.use(morgan('dev'));
app.use(express.json());
app.use(rateLimitMiddleware());
app.get('/health', (_req, res) => res.json({ status: 'ok' }));
app.use('/api/v1/auth', authRouter);
app.use('/api/v1/users', usersRouter);
app.use('/api/v1/books', booksRouter);
app.use('/api/v1/categories', categoriesRouter);
app.use('/api/v1/authors', authorsRouter);
app.use('/api/v1/borrow-records', borrowRecordsRouter);
app.use('/api/v1/reservations', reservationsRouter);
app.use('/api/v1/fines', finesRouter);
app.use(errorMiddleware);
